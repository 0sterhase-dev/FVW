const getPreferredTheme = () => {
  return window.matchMedia('(prefers-color-scheme: dark)').matches ? 'dark' : 'light';
};

const applyTheme = (theme) => {
  document.documentElement.dataset.theme = theme;
  document.documentElement.style.colorScheme = theme;
};

applyTheme(getPreferredTheme());

const colorSchemeQuery = window.matchMedia('(prefers-color-scheme: dark)');
const updateThemeFromSystem = (event) => applyTheme(event.matches ? 'dark' : 'light');

if (typeof colorSchemeQuery.addEventListener === 'function') {
  colorSchemeQuery.addEventListener('change', updateThemeFromSystem);
} else if (typeof colorSchemeQuery.addListener === 'function') {
  colorSchemeQuery.addListener(updateThemeFromSystem);
}

const menuButton = document.querySelector('.menu-button');
const mobileNav = document.querySelector('#mobileNav');
const revealItems = document.querySelectorAll('.reveal');

const detectedLocale = (() => {
  const lang = (navigator.languages && navigator.languages.length ? navigator.languages[0] : navigator.language || 'de').toLowerCase();
  return lang.startsWith('de') ? 'de' : 'en';
})();

const copy = translations[detectedLocale];

document.documentElement.lang = detectedLocale;
document.title = detectedLocale === 'de'
  ? 'Ferienhaus Valentin | Oberammergau bei München'
  : 'Holiday Home Valentin | Oberammergau near Munich';

const metaDescription = document.querySelector('meta[name="description"]');
if (metaDescription) {
  metaDescription.setAttribute(
    'content',
    detectedLocale === 'de'
      ? 'Ferienhaus in Oberammergau bei München mit Bergblick, Terrasse, 5,0 Airbnb-Sterne, Buchungslink, Bewertungen und direktem Kontakt.'
      : 'Holiday home in Oberammergau near Munich with mountain views, terrace, 5.0 Airbnb stars, booking link, reviews, and direct contact.'
  );
}

const setText = (key, value) => {
  document.querySelectorAll(`[data-i18n="${key}"]`).forEach((el) => {
    el.innerHTML = value;
  });
};

Object.entries(copy).forEach(([key, value]) => {
  setText(key, value);
});

menuButton.setAttribute('aria-label', copy.menuOpen);

const closeMenu = () => {
  mobileNav.classList.remove('is-open');
  menuButton.setAttribute('aria-expanded', 'false');
  menuButton.setAttribute('aria-label', copy.menuOpen);
};

const openMenu = () => {
  mobileNav.classList.add('is-open');
  menuButton.setAttribute('aria-expanded', 'true');
  menuButton.setAttribute('aria-label', copy.menuClose);
};

menuButton.addEventListener('click', () => {
  if (mobileNav.classList.contains('is-open')) {
    closeMenu();
  } else {
    openMenu();
  }
});

mobileNav.querySelectorAll('a').forEach((link) => {
  link.addEventListener('click', () => closeMenu());
});

document.addEventListener('click', (event) => {
  if (!mobileNav.contains(event.target) && !menuButton.contains(event.target)) {
    closeMenu();
  }
});

window.addEventListener('keydown', (event) => {
  if (event.key === 'Escape') closeMenu();
});

const observer = new IntersectionObserver((entries) => {
  for (const entry of entries) {
    if (entry.isIntersecting) {
      entry.target.classList.add('visible');
      observer.unobserve(entry.target);
    }
  }
}, { threshold: 0.15 });

revealItems.forEach((el) => observer.observe(el));

if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
  document.querySelectorAll('.reveal').forEach((el) => {
    el.classList.add('visible');
  });
}
